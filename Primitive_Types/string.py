course = "Python Programming"
print(len(course))  # counts of letters

# SLICING A STRING
print(course[0])  # first index/letter in string
print(course[-1])  # return the last index in string
print(course[0:])  # return all the string
print(course[:])  # return all the string
print(course[0:3])  # return index 0,1 and 2 in string
print(course[:3])  # return index 0,1 and 2 in string. Default 0 index.
