# INTEGER, x = 1
# FLOAT, y = 2.8
# COMPLEX, z = 1j

# ARITHMETIC OPERATIONS
# Addition
print(10 + 3)
# Subtraction
print(10 - 3)
# Multiplication
print(10 * 3)
# Standard Division: Keeps the exact decimal.
print(10 / 3)
# Floor Division: Rounds the result down to the nearest whole integer.
print(10 // 3)
# Modulus: Return the remainder of the division
print(10 % 3)
# Exponentiation: Left to the power of Right.
print(10 ** 3)

# AUGMENTED-ASSIGNMENT OPERATOR
# Unpacking a tuple matching the 7 variables
a, b, c, d, e, f, g = (10, 10, 10, 10, 10, 10, 10)
a += 3  # Or x = x + 3
b -= 3  # Or x = x - 3
c *= 3  # Or x = x * 3
d /= 3  # Or x = x / 3
e //= 3  # Or x = x // 3
f %= 3  # Or x = x % 3
g **= 3  # Or x = x ** 3
print(a)
print(b)
print(c)
print(d)
print(e)
print(f)
print(g)
