# GREATER THAN OPERATOR (>)
print("bag" > "apple")  # • ord("b") → 98 • ord("a") → 97; So, return True.

# LESS THAN OPERATOR (<)
print("bag" < "apple")

# GREATER THAN OR EQUAL TO (>=)
print("bag" >= "apple")

# LESS THAN OR EQUAL TO (<=)
print("bag" <= "apple")

# EQUALITY OPERATOR (==)
print("bag" == "apple")

# NOT EQUAL OPERATOR (!=)
print("bag" != "apple")
